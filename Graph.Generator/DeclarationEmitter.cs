using System.Text;
using Microsoft.CodeAnalysis;

namespace MASS4.Graph.Generator;

static class DeclarationEmitter
{
    internal const string Header = "// <auto-generated/>\n#nullable enable\n#pragma warning disable CS1591\nusing MASS4.Graph;\n";

    public static string Emit(Definition definition)
    {
        var text = new StringBuilder(Header);
        if (!definition.Symbol.ContainingNamespace.IsGlobalNamespace)
        {
            text.AppendLine($"namespace {definition.Symbol.ContainingNamespace.ToDisplayString()};");
        }
        var access = definition.Symbol.DeclaredAccessibility == Accessibility.Public ? "public" : "internal";
        text.AppendLine($"{access} static partial class @{definition.Symbol.Name}\n{{");
        switch (definition.Kind)
        {
            case "GraphNodeAttribute": Node(text, definition); break;
            case "GraphValueAttribute": Value(text, definition); break;
            default:
                text.AppendLine($"public static SignalType Type {{ get; }} = new({Definition.Identity(definition.Id)}, {Definition.Quote(definition.Name)});");
                break;
        }
        return text.AppendLine("}").ToString();
    }

    static void Value(StringBuilder text, Definition definition)
    {
        var value = definition.Attribute.ConstructorArguments[2];
        var type = Definition.TypeName(value);
        var serializer = Definition.NamedType(definition.Attribute, "Serializer") is { } custom
            ? $"new {custom}()"
            : Definition.NamedType(definition.Attribute, "JsonContext") is { } context
                ? JsonSerializer(type, context) : "null";
        text.AppendLine($$"""
            public static PortType Type { get; } = new({{Definition.Identity(definition.Id)}}, {{Definition.Quote(definition.Name)}})
            { ValueSerializer = {{serializer}} };
            """);
        if (value.Value is ITypeSymbol { IsUnmanagedType: true })
        {
            text.AppendLine($$"""
                public static GraphVariableHandle<{{type}}> Bind(GraphDocument document, ICompiledGraph graph, GraphVariable variable)
                    => new(document, graph, variable, Type.Id);
                """);
        }
        else
        {
            text.AppendLine($$"""
                public static GraphReferenceVariableHandle<{{type}}> Bind(GraphDocument document, ICompiledGraph graph, GraphVariable variable)
                    => new(document, graph, variable, Type.Id);
                """);
        }
    }

    static void Node(StringBuilder text, Definition definition)
    {
        var ports = Ports(definition);
        NodeType(text, definition, ports);
        NodeHelpers(text, definition, ports);
    }

    static void NodeType(StringBuilder text, Definition definition, Port[] ports)
    {
        var guard = Definition.Named<string>(definition.Attribute, "GuardType");
        if (guard is not null)
        {
            text.AppendLine($"public static NodeType Type {{ get; }} = global::MASS4.Graph.State.StateNodes.CreateGuardedTransition({Definition.Identity(definition.Id)}, {Definition.Quote(definition.Name)}, {Definition.Identity(guard)});");
        }
        else
        {
            text.AppendLine($"public static NodeType Type {{ get; }} = new({Definition.Identity(definition.Id)}, {Definition.Quote(definition.Name)}, [");
            foreach (var port in ports)
            {
                text.AppendLine($"new(Keys.@{port.Member}, {Definition.Quote(port.Name)}, (PortDirection){port.Direction}, {Definition.Identity(port.TypeId)}, (PortMultiplicity){port.Multiplicity}),");
            }
            text.AppendLine("])");
            text.AppendLine("{");
            var version = Definition.Named<int>(definition.Attribute, "Version");
            text.AppendLine($"Version = {(version == 0 ? 1 : version)},");
            if (definition.One("Payload") is { } payload)
            {
                var type = Definition.TypeName(payload.ConstructorArguments[0]);
                var serializer = Definition.NamedType(payload, "JsonContext") is { } context
                    ? JsonSerializer(type, context) : "new PayloadSerializer()";
                text.AppendLine($"PayloadSerializer = {serializer},");
                if (Definition.Named<string>(payload, "DefaultFactory") is { } factory)
                {
                    text.AppendLine($"DefaultPayload = static () => @{factory}(),");
                }
            }
            text.AppendLine("};");
        }
    }

    static void NodeHelpers(StringBuilder text, Definition definition, Port[] ports)
    {
        text.AppendLine("public static class Keys {");
        foreach (var port in ports)
        {
            text.AppendLine($"public static StableId @{port.Member} {{ get; }} = {Definition.Identity(port.Key)};");
        }
        text.AppendLine("}\npublic static class Indices {");
        for (var i = 0; i < ports.Length; i++)
        {
            text.AppendLine($"public const int @{ports[i].Member} = {i};");
        }
        text.AppendLine("}");
        Builder(text, definition, ports);
        Payload(text, definition);
        foreach (var port in ports.Where(static p => p.Direction == 1 && p.Reference))
        {
            text.AppendLine($$"""
                public static {{port.ClrType}} Reuse{{port.Member}}<TState>(global::MASS4.Graph.Dataflow.DataflowContext context,
                    TState state, global::System.Func<{{port.ClrType}}?, TState, {{port.ClrType}}> reuse)
                    => reuse(context.ReadReference<{{port.ClrType}}>(Indices.@{{port.Member}}), state);
                """);
        }
    }

    static void Builder(StringBuilder text, Definition definition, Port[] ports)
    {
        var payload = definition.One("Payload");
        var payloadType = payload is null ? "object" : Definition.TypeName(payload.ConstructorArguments[0]);
        text.AppendLine($$"""
            public static Handle Add(GraphEditor editor, {{payloadType}}? payload = null)
            {
                var command = new AddNodeCommand(Type, payload);
                TypedGraphBuilder.Require(editor, command);
                return new(command);
            }
            public readonly struct Handle(AddNodeCommand command)
            {
                public ElementId NodeId => command.NodeId;
            """);
        foreach (var port in ports)
        {
            var direction = port.Direction == 0 ? "Input" : "Output";
            text.AppendLine($"public Graph{direction}<{port.ClrType}> @{port.Member} => new(command.PortId(Keys.@{port.Member}));");
        }
        text.AppendLine("}");
        var behavior = definition.One("Behavior");
        if (Definition.Named<string>(definition.Attribute, "GuardType") is not null ||
            behavior?.ConstructorArguments[0].Value is 3)
        {
            text.AppendLine($$"""
                public static Handle Transition(GraphEditor editor, GraphOutput<StateFlow> from, GraphInput<StateFlow> to,
                    {{payloadType}}? payload = null, StableId? trigger = null, int priority = 0)
                {
                    var node = new AddNodeCommand(Type, payload)
                    { Annotations = global::MASS4.Graph.State.StateNodes.Annotations(trigger, priority) };
                    TypedGraphBuilder.Require(editor, new CompositeCommand("Add transition", [node,
                        new ConnectCommand(from.Id, node.PortId(global::MASS4.Graph.State.StateNodes.FromKey)),
                        new ConnectCommand(node.PortId(global::MASS4.Graph.State.StateNodes.ToKey), to.Id)]));
                    return new(node);
                }
                """);
        }
    }

    static void Payload(StringBuilder text, Definition definition)
    {
        if (definition.One("Payload") is not { } payload || Definition.NamedType(payload, "Value") is not { } value)
        {
            return;
        }
        var type = Definition.TypeName(payload.ConstructorArguments[0]);
        var member = Definition.Named<string>(payload, "Member") ?? "Value";
        var declaration = (INamedTypeSymbol)Definition.Named<ITypeSymbol>(payload, "Value")!;
        var valueAttribute = declaration.GetAttributes().First(static a =>
            a.AttributeClass?.ToDisplayString() == RegistrationGenerator.Prefix + "ValueAttribute");
        var valueType = Definition.TypeName(valueAttribute.ConstructorArguments[2]);
        text.AppendLine($$"""
            sealed class PayloadSerializer : IValueSerializer
            {
                public void Write(global::System.Text.Json.Utf8JsonWriter writer, object? payload)
                    => {{value}}.Type.ValueSerializer!.Write(writer, (({{type}})payload!).@{{member}});
                public object? Read(global::System.Text.Json.JsonElement element)
                    => new {{type}}(({{valueType}}){{value}}.Type.ValueSerializer!.Read(element)!);
            }
            """);
    }

    static string JsonSerializer(string type, string context) =>
        $"new JsonTypeInfoSerializer<{type}>((global::System.Text.Json.Serialization.Metadata.JsonTypeInfo<{type}>)({context}.Default.GetTypeInfo(typeof({type})) ?? throw new global::System.InvalidOperationException(\"Missing generated JSON metadata.\")))";

    internal static Port[] Ports(Definition definition)
    {
        if (Definition.Named<string>(definition.Attribute, "GuardType") is { } guard)
        {
            return
            [
                new("From", "4d415353-3447-5241-5048-000000000214", "from", 0,
                    "4d415353-3447-5241-5048-000000000201", "global::MASS4.Graph.StateFlow", 0, false),
                new("To", "4d415353-3447-5241-5048-000000000215", "to", 1,
                    "4d415353-3447-5241-5048-000000000201", "global::MASS4.Graph.StateFlow", 0, false),
                new("Condition", "4d415353-3447-5241-5048-000000000216", "condition", 0, guard, "bool", 0, false),
            ];
        }
        return [.. definition.Ports.Select(static attribute =>
        {
            var args = attribute.ConstructorArguments;
            var direction = (int)args[3].Value!;
            var multiplicity = attribute.NamedArguments.FirstOrDefault(static p => p.Key == "Multiplicity");
            return new Port((string)args[0].Value!, (string)args[1].Value!, (string)args[2].Value!, direction,
                (string)args[4].Value!, Definition.TypeName(args[5]),
                multiplicity.Key is null ? direction : (int)multiplicity.Value.Value!,
                ((ITypeSymbol)args[5].Value!).IsReferenceType);
        })];
    }

    internal sealed record Port(string Member, string Key, string Name, int Direction, string TypeId,
        string ClrType, int Multiplicity, bool Reference);
}
